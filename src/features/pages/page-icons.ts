/** All emojis of the picker, in their order. */
const PAGE_ICONS: readonly string[] = ICONS.map((icon) => icon.emoji);

/** Emojis whose German words start with what was typed (any word of the query). */
export function searchIcons(query: string): string[] {
    const terms = query.trim().toLocaleLowerCase("de").split(/\s+/).filter(Boolean);
    if (terms.length === 0) return [...PAGE_ICONS];
    return ICONS.filter(({ words }) => {
        const list = words.split(" ");
        return terms.every((term) => list.some((word) => word.startsWith(term)));
    }).map((icon) => icon.emoji);
}

const ONE_EMOJI =
    /^(?:\p{Extended_Pictographic}|\p{Regional_Indicator}{2})(?:️|‍\p{Extended_Pictographic}|\p{Emoji_Modifier})*$/u;

/** An emoji typed or pasted into the search, to use it although it is not in the list. */
export function typedEmoji(query: string): string | null {
    const text = query.trim();
    return ONE_EMOJI.test(text) ? text : null;
}
